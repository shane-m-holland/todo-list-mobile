#!/usr/bin/env bash
# End-to-end journey: real backend + the Android app on an emulator, driven like a user would.
#
#   scripts/e2e/android-journey.sh                    # in-memory backend (default)
#   E2E_TARGET=postgres scripts/e2e/android-journey.sh   # Postgres backend, restarted mid-journey
#   E2E_TARGET=mock     scripts/e2e/android-journey.sh   # the WireMock mock instead of the backend
#   E2E_PUBLISH=1 ...                                 # on success, refresh docs/e2e/android-journey/
#
# After every step it checks the screen AND the server. Writes build/e2e/<run>/journey.md with
# screenshots, the backend's state after each step, and the result. Exit code 0 only if every check passed.
set -euo pipefail

# shellcheck source=lib.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib.sh"

TARGET="${E2E_TARGET:-memory}"
case "$TARGET" in
  memory)   PROFILE=memory;   FLAVOR=local; FLAVOR_TASK=Local; PORT=8081; RESTART_MIDWAY=0 ;;
  postgres) PROFILE=postgres; FLAVOR=local; FLAVOR_TASK=Local; PORT=8081; RESTART_MIDWAY=1 ;;
  mock)     PROFILE="";       FLAVOR=mock;  FLAVOR_TASK=Mock;  PORT=8080; RESTART_MIDWAY=0 ;;
  *) die "E2E_TARGET must be memory, postgres or mock (got '$TARGET')" ;;
esac
APP_ID="com.example.todo.$FLAVOR"
API="http://localhost:$PORT/api/v1"
MOCK_ADMIN="http://localhost:8080/__admin"

RUN_ID="$(date -u +%Y%m%dT%H%M%SZ)-$TARGET"
OUT="$ROOT/build/e2e/$RUN_ID"
BODY="$OUT/body.md"
mkdir -p "$OUT/raw" "$OUT/img"
: > "$BODY"
ln -sfn "$OUT" "$ROOT/build/e2e/latest"

BACKEND_PID=""
BACKEND_RUNS=0
STARTED_AT="$(date -u '+%Y-%m-%d %H:%M UTC')"
SAVED_ANIMATIONS=""

# ---- backend lifecycle ---------------------------------------------------------------------------------
backend_up() { curl -fs "http://localhost:$PORT/actuator/health" > /dev/null 2>&1; }

backend_start() {
  BACKEND_RUNS=$((BACKEND_RUNS + 1))
  env SERVER_PORT="$PORT" SPRING_PROFILES_ACTIVE="$PROFILE" TODO_SEED_ENABLED=false \
    "$JDK21_HOME/bin/java" -jar "$JAR" > "$OUT/backend-$BACKEND_RUNS.log" 2>&1 &
  BACKEND_PID=$!
  wait_for 90 backend_up || fail "the backend did not become healthy (see backend-$BACKEND_RUNS.log)"
}

backend_stop() {
  if [[ -n "$BACKEND_PID" ]]; then
    kill "$BACKEND_PID" 2> /dev/null || true
    wait "$BACKEND_PID" 2> /dev/null || true
    BACKEND_PID=""
  fi
}

# "The server is down" for the error phase: stop the process, or switch on the mock's failure mode.
server_break() {
  if [[ "$TARGET" == mock ]]; then
    curl -fsS -o /dev/null -X PUT "$MOCK_ADMIN/scenarios/failure-mode/state" -d '{"state":"failing"}'
  else
    backend_stop
  fi
}
server_fix() {
  if [[ "$TARGET" == mock ]]; then
    curl -fsS -o /dev/null -X PUT "$MOCK_ADMIN/scenarios/failure-mode/state"
  else
    backend_start
  fi
}

# ---- the report ------------------------------------------------------------------------------------------
write_report() {
  local result="PASS ✅" elapsed=$((SECONDS - START_SECONDS))
  if [[ -n "$FAILED_AT" ]]; then result="FAIL ❌ — $FAILED_AT"; fi
  local sha dirty=""
  sha=$(git -C "$ROOT" rev-parse --short HEAD 2> /dev/null || echo unknown)
  if [[ -n "$(git -C "$ROOT" status --porcelain 2> /dev/null)" ]]; then dirty=" (+ uncommitted changes)"; fi
  local device android_version
  device=$("$ADB" shell getprop ro.product.model 2> /dev/null | tr -d '\r' || true)
  android_version=$("$ADB" shell getprop ro.build.version.release 2> /dev/null | tr -d '\r' || true)
  {
    echo "# Android end-to-end journey"
    echo
    echo "The ToDo app on a real Android emulator talking to a real server, driven like a user, with every step"
    echo "checked on the screen **and** on the server. Generated by \`scripts/e2e/android-journey.sh\`."
    echo
    echo "| | |"
    echo "|---|---|"
    echo "| **Result** | $result |"
    echo "| **Checks passed** | $CHECKS |"
    echo "| **Server** | $(describe_target) |"
    echo "| **App** | \`$APP_ID\` (debug) on ${device:-?}, Android ${android_version:-?} |"
    echo "| **Run** | $STARTED_AT, ${elapsed}s, commit \`$sha\`$dirty |"
    echo
    echo "Re-run: \`make e2e-android\` (also \`E2E_TARGET=postgres\` or \`mock\`, and \`E2E_PUBLISH=1\` to refresh this page)."
    cat "$BODY"
  } > "$OUT/journey.md"
}

describe_target() {
  case "$TARGET" in
    memory) echo "Spring Boot backend, in-memory storage (\`$API\`)" ;;
    postgres) echo "Spring Boot backend, PostgreSQL storage (\`$API\`)" ;;
    mock) echo "WireMock mock (\`$API\`)" ;;
  esac
}

finish() {
  local code=$?
  trap - EXIT
  set +e # cleanup must run to the end, and the report must be written, whatever fails
  if [[ $code -ne 0 && -z "$FAILED_AT" ]]; then FAILED_AT="the script stopped unexpectedly (exit $code)"; fi
  backend_stop
  if [[ "$TARGET" == mock ]]; then curl -fs -o /dev/null -X PUT "$MOCK_ADMIN/scenarios/failure-mode/state" 2> /dev/null || true; fi
  restore_animations
  write_report
  log ""
  log "Report: $OUT/journey.md"
  if [[ -z "$FAILED_AT" && "${E2E_PUBLISH:-0}" == 1 ]]; then publish_docs; fi
  exit "$code"
}
trap finish EXIT

publish_docs() {
  local dest="$ROOT/docs/e2e/android-journey"
  rm -rf "$dest"; mkdir -p "$dest"
  cp -R "$OUT/img" "$dest/img"
  cp "$OUT/journey.md" "$dest/README.md"
  log "Published to ${dest#"$ROOT"/}/README.md"
}

# ---- emulator ---------------------------------------------------------------------------------------------
boot_done() { [[ "$("$ADB" shell getprop sys.boot_completed 2> /dev/null | tr -d '\r')" == 1 ]]; }
device_present() { "$ADB" devices | awk 'NR > 1 && $2 == "device"' | grep -q .; }

ensure_emulator() {
  if ! device_present; then
    local avd="${E2E_AVD:-$("$EMULATOR" -list-avds | head -1)}"
    [[ -n "$avd" ]] || die "no emulator running and no AVD found"
    log "Booting emulator $avd (it stays running afterwards)"
    "$EMULATOR" -avd "$avd" -no-snapshot-save -no-boot-anim > "$OUT/emulator.log" 2>&1 &
    disown
    wait_for 120 device_present || die "emulator did not appear"
  fi
  wait_for 240 boot_done || die "emulator did not finish booting"
}

# Animations make taps race the UI, so switch them off for the run and put them back afterwards.
disable_animations() {
  local key
  SAVED_ANIMATIONS=""
  for key in window_animation_scale transition_animation_scale animator_duration_scale; do
    SAVED_ANIMATIONS="$SAVED_ANIMATIONS $key=$("$ADB" shell settings get global "$key" | tr -d '\r')"
    "$ADB" shell settings put global "$key" 0
  done
}
restore_animations() {
  local pair
  for pair in $SAVED_ANIMATIONS; do
    if [[ "${pair#*=}" == null ]]; then "$ADB" shell settings put global "${pair%%=*}" 1.0
    else "$ADB" shell settings put global "${pair%%=*}" "${pair#*=}"; fi
  done
}

# ---- setup -------------------------------------------------------------------------------------------------
section "Setup"
for tool in curl jq python3 sips; do command -v "$tool" > /dev/null || die "$tool is required"; done
[[ -x "$ADB" ]] || die "adb not found at $ADB (set ANDROID_SDK)"
[[ -x "$JDK21_HOME/bin/java" ]] || die "no JDK 21 at $JDK21_HOME (set JDK21_HOME)"

if [[ "$TARGET" != mock ]]; then
  # Listeners only: the emulator may still hold client connections to a server that just stopped.
  if [[ -n "$(lsof -nP -iTCP:"$PORT" -sTCP:LISTEN -t 2> /dev/null)" ]]; then
    die "port $PORT is already in use. Stop whatever is listening: this script will not kill it for you."
  fi
  log "Building the backend jar"
  (cd "$ROOT/backend" && JAVA_HOME="$JDK21_HOME" ./gradlew --console=plain -q bootJar > "$OUT/build-backend.log" 2>&1) \
    || die "backend build failed (see $OUT/build-backend.log)"
  JAR=$(find "$ROOT/backend/build/libs" -name 'todo-backend-*.jar' ! -name '*-plain.jar' | head -1)
  [[ -n "$JAR" ]] || die "no backend jar found"
fi
if [[ "$TARGET" == postgres ]]; then
  "$CONTAINER" ps --format '{{.Names}}' | grep -qx todo-db || make -C "$ROOT" db-up > "$OUT/db-up.log" 2>&1 \
    || die "could not start the local PostgreSQL (make db-up)"
fi
if [[ "$TARGET" == mock ]]; then
  curl -fs "$MOCK_ADMIN/health" > /dev/null || make -C "$ROOT" mock-up > "$OUT/mock-up.log" 2>&1 \
    || die "could not start the mock (make mock-up)"
fi

ensure_emulator
log "Building and installing the app ($FLAVOR flavor)"
(cd "$ROOT/android" && JAVA_HOME="$JDK21_HOME" ./gradlew --console=plain -q ":app:install${FLAVOR_TASK}Debug" > "$OUT/build-android.log" 2>&1) \
  || die "app build/install failed (see $OUT/build-android.log)"
disable_animations
"$ADB" shell pm clear "$APP_ID" > /dev/null
md "- Emulator ready, animations off, app data cleared (\`pm clear\`), \`$APP_ID\` freshly installed."
md "- The server starts **empty** (seeding off), so the list holds exactly what this journey creates."

# ---- the journey -------------------------------------------------------------------------------------------
section "The journey" "Steps 1–12 are the journey as specified. Each ends with the screen and the server's view of the world."

step 1 "Start the backend" "Starts the server on port $PORT and empties it."
case "$TARGET" in
  mock)
    curl -fsS -o /dev/null -X DELETE "$MOCK_ADMIN/state-extension/contexts"
    curl -fsS -o /dev/null -X POST "$MOCK_ADMIN/scenarios/reset"
    ;;
  postgres)
    backend_start
    "$CONTAINER" exec todo-db psql -U todo -d todo -q -c 'TRUNCATE todos' > /dev/null
    ;;
  *) backend_start ;;
esac
pass "The server answers on $API"
expect_eq "The server starts with no todos" 0 "$(server_count)"
snapshot_md

step 2 "Start the Android app" "Launches the app on the emulator."
app_start
wait_for 30 ui_exists --desc "Add todo" || fail "the app did not reach its main screen"
wait_for 10 ui_exists --text-re "Nothing to do yet" || fail "the empty-state hint never appeared"
pass "The app is running and shows its empty state"
assert_open_count
assert_ui_matches_server "Step 2"
shot launched "The app on first launch: empty list"

step 3 "Create a task: Walk the dog" "Taps +, types the title, taps Save."
add_todo "Walk the dog"
expect_eq "The server has the todo" "Walk the dog" "$(server_titles)"
expect_eq "It starts not completed" false "$(server_field "Walk the dog" completed)"
assert_open_count
shot walk-the-dog "Walk the dog added"
snapshot_md

step 4 "Create a task: Grocery shopping" "Same again."
add_todo "Grocery shopping"
expect_eq "The server has both, in creation order" "Walk the dog, Grocery shopping" "$(server_titles)"
assert_ui_matches_server "Step 4"
assert_open_count
shot grocery-shopping "Both todos listed"
snapshot_md

step 5 "Complete a task: Walk the dog" "Taps the checkbox next to it."
complete_todo "Walk the dog"
expect_eq "The server marks it completed" true "$(server_field "Walk the dog" completed)"
expect_eq "Grocery shopping is untouched" false "$(server_field "Grocery shopping" completed)"
assert_open_count
shot walk-completed "Walk the dog completed"
snapshot_md

step 6 "Close the app" "Force-stops the process, so nothing in memory survives."
app_stop
wait_for 5 app_gone || fail "the app process is still alive"
pass "The app process is gone"
# While the app is closed, change something it could not know about, so step 7 can only pass
# if the app really fetches from the server.
WALK_ID=$(server_id "Walk the dog")
GROCERY_ID=$(server_id "Grocery shopping")
GROCERY_NOTE="Edited on the server while the app was closed"
if [[ "$RESTART_MIDWAY" == 1 ]]; then
  backend_stop; backend_start
  expect_eq "The backend was restarted and PostgreSQL still has both todos" "Walk the dog, Grocery shopping" "$(server_titles)"
  expect_eq "Walk the dog is still completed after the restart" true "$(server_field "Walk the dog" completed)"
fi
curl -fsS -o /dev/null -X PATCH "$API/todos/$GROCERY_ID" -H 'Content-Type: application/json' \
  -d "{\"notes\":\"$GROCERY_NOTE\"}"
expect_eq "Server-side edit applied while the app is closed" "$GROCERY_NOTE" "$(server_field "Grocery shopping" notes)"
shot app-closed "Launcher with the app closed"
snapshot_md

step 7 "Open the app" "Cold start. The state must come from the server."
app_start
wait_for 30 ui_exists --desc "Complete Grocery shopping" || fail "the todos did not load after reopening"
expect_eq "Walk the dog is still completed" true "$("${UI[@]}" rows | jq -r '.[] | select(.title == "Walk the dog") | .completed')"
if wait_for 10 ui_exists --text "$GROCERY_NOTE"; then
  pass "The note that was added on the server (and never seen by the app) is on screen"
else
  fail "the server-side note is not on screen: the app is not reading from the server"
fi
assert_ui_matches_server "Step 7"
assert_open_count
shot reopened "App reopened with state from the server"

step 8 "Delete the Walk the dog task" "Swipes the row away."
delete_todo "Walk the dog"
expect_eq "The server no longer lists it" "Grocery shopping" "$(server_titles)"
expect_eq "Fetching it by id returns 404" 404 "$(curl -s -o /dev/null -w '%{http_code}' "$API/todos/$WALK_ID")"
assert_ui_matches_server "Step 8"
shot walk-deleted "Walk the dog deleted"
snapshot_md

step 9 "Complete the Grocery shopping task" "Taps its checkbox."
complete_todo "Grocery shopping"
expect_eq "The server marks it completed" true "$(server_field "Grocery shopping" completed)"
assert_open_count
shot grocery-completed "Grocery shopping completed"
snapshot_md

step 10 "Add a task: Make dinner reservation" "Taps +, types the title, taps Save."
add_todo "Make dinner reservation"
expect_eq "The server has both, in creation order" "Grocery shopping, Make dinner reservation" "$(server_titles)"
expect_eq "The new one is not completed" false "$(server_field "Make dinner reservation" completed)"
assert_open_count
shot dinner-added "Make dinner reservation added"
snapshot_md

step 11 "Close the app" "Force-stops it again, then edits the server behind its back."
app_stop
wait_for 5 app_gone || fail "the app process is still alive"
pass "The app process is gone"
DINNER_ID=$(server_id "Make dinner reservation")
DINNER_NOTE="Table for two at 7pm"
curl -fsS -o /dev/null -X PATCH "$API/todos/$DINNER_ID" -H 'Content-Type: application/json' \
  -d "{\"notes\":\"$DINNER_NOTE\"}"
expect_eq "Server-side edit applied while the app is closed" "$DINNER_NOTE" "$(server_field "Make dinner reservation" notes)"
shot app-closed-again "Launcher with the app closed"
snapshot_md

step 12 "Open the app" "Cold start. Final state must match the server."
app_start
wait_for 30 ui_exists --desc "Complete Make dinner reservation" || fail "the todos did not load after reopening"
if wait_for 10 ui_exists --text "$DINNER_NOTE"; then
  pass "The server-side note is on screen"
else
  fail "the server-side note is not on screen: the app is not reading from the server"
fi
expect_eq "Grocery shopping is completed" true "$("${UI[@]}" rows | jq -r '.[] | select(.title == "Grocery shopping") | .completed')"
expect_eq "Make dinner reservation is still open" false "$("${UI[@]}" rows | jq -r '.[] | select(.title == "Make dinner reservation") | .completed')"
expect_eq "Walk the dog stays deleted" 0 "$("${UI[@]}" rows | jq '[.[] | select(.title == "Walk the dog")] | length')"
assert_ui_matches_server "Step 12"
assert_open_count
shot final "Final state"
snapshot_md

# ---- extra: the server goes away ---------------------------------------------------------------------------------
section "Extra: the server goes away" "Not part of the original journey. Checks that the app fails gracefully and recovers on its own."
server_break
if [[ "$TARGET" == mock ]]; then
  pass "Mock failure mode on: every call returns 500"
else
  pass "Backend stopped: connections are refused"
fi
ui_pull_to_refresh
if wait_for 20 ui_exists --text-re "Couldn't refresh"; then
  pass "A refresh failure is reported in a snackbar"
else
  fail "no \"Couldn't refresh\" message after pulling to refresh with the server down"
fi
expect_eq "The list stays on screen instead of being wiped" 2 "$("${UI[@]}" rows | jq length)"
shot server-down "Server down: the list stays, a message explains"
server_fix
pass "The server is back"
if [[ "$TARGET" == memory ]]; then
  md "- ℹ️ The in-memory backend lost its data when it restarted, so it is empty now. That is expected for this profile."
fi
# The first pull can land while the previous snackbar is still animating out, so allow a few tries.
recovered=0
for attempt in 1 2 3; do
  ui_pull_to_refresh
  if wait_for 15 ui_matches_server; then recovered=1; break; fi
done
if [[ "$recovered" == 1 ]]; then pass "After one more pull to refresh the screen matches the server again"
else fail "the app never recovered after the server came back"; fi
shot recovered "Server back: screen matches again"
snapshot_md

section "Result" "Every check above passed."
